/* JOINT service worker: display-only push handling; no fetch interception or cache changes. */
self.addEventListener('push', event => {
  let payload = {};
  try { payload = event.data ? event.data.json() : {}; }
  catch (_) { payload = { body: event.data ? event.data.text() : '' }; }

  const title = payload.title || 'JOINT notification';
  const avatar = payload.actor_avatar_url || payload.avatar_url || payload.icon || '/icons/icon-192.png';
  const mediaType = String(payload.attachment_type || payload.media_type || '').toLowerCase();
  const attachmentUrl = payload.attachment_url || payload.media_url || '';
  // NotificationOptions.image accepts an image resource, not an MP4 stream.
  // Video notifications therefore use the JPEG poster generated by chat-backend.js.
  const preview = payload.attachment_preview_url || payload.thumbnail_url || payload.image ||
    ((!mediaType.includes('video') && /\.(png|jpe?g|gif|webp|avif)(?:[?#]|$)/i.test(attachmentUrl)) ? attachmentUrl : '');

  const options = {
    body: payload.body || 'You have a new notification on JOINT.',
    icon: avatar,
    image: preview || undefined,
    badge: payload.badge || '/icons/icon-192.png',
    data: {
      url: payload.url || payload.target_url || '/notifications.html',
      attachment_url: attachmentUrl,
      attachment_type: mediaType,
      attachment_preview_url: preview
    },
    tag: payload.tag || payload.notification_id || undefined,
    renotify: false
  };
  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener('notificationclick', event => {
  event.notification.close();
  const destination = new URL((event.notification.data && event.notification.data.url) || '/notifications.html', self.location.origin).href;
  event.waitUntil((async () => {
    const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    for (const client of windows) {
      if (client.url.startsWith(self.location.origin) && 'focus' in client) {
        await client.focus();
        if ('navigate' in client) await client.navigate(destination);
        return;
      }
    }
    if (self.clients.openWindow) await self.clients.openWindow(destination);
  })());
});
